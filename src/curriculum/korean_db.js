/** DB 무결성 검증 — 테스트와 앱 시작 시 사용 */
export function validateDb() {
  const problems = [];
  const seen = new Set();
  for (const p of PAIRS) {
    if (!p.c || !p.w || !p.hint) problems.push(`빈 필드: ${JSON.stringify(p)}`);
    if (p.c === p.w) problems.push(`정답=오답: ${p.c}`);
    const key = `${p.hint}|${p.c}`;
    if (seen.has(key)) problems.push(`중복 쌍: ${key}`);
    seen.add(key);
  }
  const sSeen = new Set();
  for (const s of SENTENCES) {
    if (s !== s.trim()) problems.push(`양끝 공백: "${s}"`);
    const n = s.split(' ').length;
    if (n < 2 || n > 4) problems.push(`어절 수 이상(${n}): "${s}"`);
    if (sSeen.has(s)) problems.push(`중복 문장: "${s}"`);
    sSeen.add(s);
  }
  return { ok: problems.length === 0, problems };
}

/** K-3 징검다리 문제 1개 (좌우 랜덤 배치) */
export function makeStoneProblem(rand = Math.random) {
  const p = pick(PAIRS, rand);
  const correctFirst = rand() < 0.5;
  return {
    hint: p.hint,
    options: correctFirst ? [p.c, p.w] : [p.w, p.c],
    answer: p.c,
  };
}
